def insert_block(text, new_block):
    anchor_a = '"analytics.'
    anchor_b = '"auth.'
    # 在 analytics 段结束后、auth 段开始前插入
    ia = text.find(anchor_a)
    ib = text.find(anchor_b)
    if ia == -1 or ib == -1:
        raise RuntimeError(f"anchor not found: a={ia} b={ib}")
    # 找 auth 段起始行的行首
    line_start = text.rfind("\n", 0, ib) + 1
    return text[:line_start] + new_block + text[line_start:]

def build_block(data, prefix="application"):
    lines = []
    for k in sorted(data):
        v = json.dumps(data[k], ensure_ascii=False)
        lines.append(f'    "{prefix}.{k}": {v},')
    return "\n".join(lines) + "\n"

for lang, data in (("en", en), ("zh-cn", zh)):
    path = os.path.join(repo, "lang", f"{lang}.json")
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    block = build_block(data)
    new_text = insert_block(text, block)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new_text)
    print(f"{lang}.json updated, inserted {len(data)} keys")

